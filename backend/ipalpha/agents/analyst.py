"""Quantitative Analyst Agent: when a company's hype and price diverge, it pulls the numbers and
the most relevant recent posts and writes a structured, cited thesis."""

import datetime as dt
import logging
from typing import Literal

from pydantic import BaseModel, Field
from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from ipalpha.agents import tools
from ipalpha.agents.citations import audit_citations
from ipalpha.agents.common import dead_letter
from ipalpha.config import Settings
from ipalpha.db.models import Company, HypeScore, Thesis
from ipalpha.ingestion.common import JST
from ipalpha.llm import LLM, Message, StructuredOutputError

log = logging.getLogger(__name__)

DISCLAIMER = "Generated by a language model from public fan activity. Not investment advice."
LOOKBACK_DAYS = 7
MAX_DOCUMENTS = 10


class Evidence(BaseModel):
    document_id: int
    point: str = Field(description="What this document shows, in one sentence")


class ThesisDraft(BaseModel):
    headline: str = Field(description="Under 15 words")
    stance: Literal["hype_ahead_of_price", "price_ahead_of_hype", "no_clear_signal"]
    claim: str = Field(description="2-4 sentences connecting the fan activity to the price")
    evidence: list[Evidence]
    risks: list[str] = Field(description="1-4 reasons the claim could be wrong")
    confidence: float = Field(ge=0, le=1)


SYSTEM_PROMPT = """You are a quantitative analyst covering Japanese entertainment companies. \
A Hype Score is a z-score of fan activity (players, reviews, MyAnimeList, Oricon sales, social \
mentions) against its own 28-day baseline; divergence is company hype minus the z-score of the \
stock's 5-day return over the Nikkei 225. Positive divergence means hype is ahead of the price.

Using only the facts and documents provided, explain what is driving the divergence. Cite \
documents by their numeric id in `evidence`; never cite an id that is not listed. Use stance \
hype_ahead_of_price for positive divergence and price_ahead_of_hype for negative divergence when \
the documents explain it. Use no_clear_signal only if they don't, and then keep confidence low. \
Do not recommend buying or selling."""


def build_messages(snapshot: tools.Snapshot, docs: list[tools.DocHit]) -> list[Message]:
    documents = "\n".join(d.prompt_line() for d in docs) or "(no documents in the window)"
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": f"Facts:\n{snapshot.prompt_block()}\n\n"
            f"Documents from the last {LOOKBACK_DAYS} days:\n{documents}",
        },
    ]


def check_citations(draft: ThesisDraft, docs: list[tools.DocHit]) -> tuple[list[dict], list[int]]:
    """Keep evidence that cites a document the model was shown; return the rest separately."""
    by_id = {d.id: d for d in docs}
    valid, invalid = [], []
    for ev in draft.evidence:
        doc = by_id.get(ev.document_id)
        if doc is None:
            invalid.append(ev.document_id)
            continue
        valid.append(
            {
                "document_id": doc.id,
                "point": ev.point,
                "source": doc.source,
                "url": doc.url,
                "published_at": doc.published_at.isoformat(),
            }
        )
    return valid, invalid


def write_thesis(
    session: Session, llm: LLM, company: Company, hype_row: HypeScore
) -> Thesis | None:
    snap = tools.snapshot(session, company, until=hype_row.date)
    end = dt.datetime.combine(hype_row.date + dt.timedelta(days=1), dt.time(), JST)
    top = ", ".join(ip.name for ip in snap.top_ips) or company.name
    docs = tools.search_documents(
        session,
        llm,
        f"{company.name} {top} news announcement release sales",
        ip_ids=tools.company_ip_ids(company),
        since=end - dt.timedelta(days=LOOKBACK_DAYS),
        limit=MAX_DOCUMENTS,
    )
    docs = [d for d in docs if d.published_at < end]
    try:
        result = llm.structured(build_messages(snap, docs), ThesisDraft)
    except StructuredOutputError as exc:
        log.warning("thesis for %s failed validation: %s", company.ticker, exc)
        dead_letter(session, "analyze", f"thesis:{company.ticker}:{hype_row.date}", str(exc))
        session.commit()
        return None

    evidence, _ = check_citations(result.value, docs)
    audit = audit_citations(
        session,
        [ev.document_id for ev in result.value.evidence],
        [d.id for d in docs],
        [company.ticker],
    )
    valid_ids = set(audit.valid)
    evidence = [row for row in evidence if row["document_id"] in valid_ids]
    dropped = audit.unknown + audit.missing + audit.unrelated
    if dropped:
        log.warning("thesis for %s dropped citations %s", company.ticker, dropped)
    body = result.value.model_dump()
    body.update(
        evidence=evidence,
        dropped_citations=dropped,
        citation_audit=audit.model_dump(),
        disclaimer=DISCLAIMER,
        inputs={
            "hype": snap.hype,
            "divergence": snap.divergence,
            "return_z": snap.return_z,
            "return_5d": snap.return_5d,
            "documents": len(docs),
        },
    )
    thesis = Thesis(
        ticker=company.ticker,
        date=hype_row.date,
        divergence=hype_row.divergence,
        body=body,
        model=llm.chat_model,
        tokens=result.tokens,
        latency_ms=result.latency_ms,
    )
    session.add(thesis)
    session.commit()
    return thesis


def run(
    session: Session,
    llm: LLM,
    settings: Settings,
    *,
    tickers: list[str] | None = None,
    force: bool = False,
) -> dict[str, int]:
    """One thesis per company per scored day, only when |divergence| crosses the threshold
    (or always, with force=True, which also replaces an existing thesis for that day)."""
    stats = {"written": 0, "skipped": 0, "failed": 0}
    for company in tools.companies_with_ownerships(session):
        if tickers and company.ticker not in tickers:
            continue
        row = session.scalars(
            select(HypeScore)
            .where(HypeScore.company_id == company.id)
            .order_by(HypeScore.date.desc())
            .limit(1)
        ).first()
        if row is None:
            stats["skipped"] += 1
            continue
        divergent = (
            row.divergence is not None and abs(row.divergence) >= settings.analyst_min_divergence
        )
        exists = session.scalar(
            select(Thesis.id).where(Thesis.ticker == company.ticker, Thesis.date == row.date)
        )
        if not force and (not divergent or exists):
            stats["skipped"] += 1
            continue
        if exists:
            session.execute(
                delete(Thesis).where(Thesis.ticker == company.ticker, Thesis.date == row.date)
            )
        if write_thesis(session, llm, company, row):
            stats["written"] += 1
        else:
            stats["failed"] += 1
    log.info("analyze: %s", stats)
    return stats
